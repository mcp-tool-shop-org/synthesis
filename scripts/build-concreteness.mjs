#!/usr/bin/env node
/**
 * Regenerate src/checks/lexicons/concreteness.ts from the public Brysbaert norms.
 *
 * Source: Brysbaert, M., Warriner, A. B., & Kuperman, V. (2014). "Concreteness
 * ratings for 40 thousand generally known English word lemmas." Behavior Research
 * Methods, 46(3), 904-911. doi:10.3758/s13428-013-0403-5
 * Public mirror used to build the shipped subset:
 *   https://raw.githubusercontent.com/ArtsEngine/concreteness/master/Concreteness_ratings_Brysbaert_et_al_BRM.txt
 *
 * This script is COMMITTED but NOT shipped (scripts/ is excluded from the package
 * `files` allowlist). It exists for provenance + reproducibility: the runtime never
 * regenerates, so the checker is deterministic (same input -> same output).
 *
 * Usage: node scripts/build-concreteness.mjs <path-to-Concreteness_ratings_Brysbaert_et_al_BRM.txt>
 */
import { readFileSync, writeFileSync } from 'node:fs';

const TOP_N = 3000; // most-frequent single words (SUBTLEX); bounded, ~80KB artifact
const MIN_LEN = 3;
const MIN_KNOWN = 0.9;

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-concreteness.mjs <brysbaert.txt>');
  process.exit(1);
}

const lines = readFileSync(src, 'utf-8').split(/\r?\n/);
const header = lines[0].split('\t');
const iWord = header.indexOf('Word');
const iBigram = header.indexOf('Bigram');
const iConc = header.indexOf('Conc.M');
const iKnown = header.indexOf('Percent_known');
const iFreq = header.indexOf('SUBTLEX');
if ([iWord, iBigram, iConc, iKnown, iFreq].some((x) => x < 0)) {
  console.error('unexpected header columns:', header);
  process.exit(1);
}

const rows = [];
for (let i = 1; i < lines.length; i++) {
  const f = lines[i].split('\t');
  if (f.length < header.length) continue;
  const word = f[iWord].toLowerCase().trim();
  if (f[iBigram] !== '0') continue; // single words only, never bigrams
  if (!/^[a-z]+$/.test(word)) continue; // ascii letters only
  if (word.length < MIN_LEN) continue;
  const known = parseFloat(f[iKnown]);
  if (!(known >= MIN_KNOWN)) continue;
  const conc = parseFloat(f[iConc]);
  if (!(conc >= 1 && conc <= 5)) continue;
  const freq = parseInt(f[iFreq], 10) || 0;
  rows.push({ word, conc, freq });
}

rows.sort((a, b) => b.freq - a.freq); // by frequency
const picked = rows.slice(0, TOP_N);
picked.sort((a, b) => a.word.localeCompare(b.word, 'en')); // alpha for stable diffs

const entries = picked
  .map((r) => `  ${JSON.stringify(r.word)}: ${Math.round(r.conc * 100) / 100},`)
  .join('\n');

const out = `/**
 * Concreteness ratings — curated subset of Brysbaert, Warriner & Kuperman (2014),
 * "Concreteness ratings for 40 thousand generally known English word lemmas",
 * Behavior Research Methods 46(3):904-911, doi:10.3758/s13428-013-0403-5.
 *
 * Values are the PUBLISHED Conc.M means on a 1.0 (abstract) - 5.0 (concrete) scale.
 * The runtime rescales to [0,1] as (rating - 1) / 4. Words ABSENT here are IGNORED
 * (never scored 0); when fewer than MIN_CONCRETENESS_TOKENS assistant content words
 * are found in this map, the concreteness signal is dropped entirely from the
 * particularity blend (register-bias guard — never punish simple/non-native vocab).
 *
 * GENERATED by scripts/build-concreteness.mjs (top ${TOP_N} single words by SUBTLEX
 * frequency, length >= ${MIN_LEN}, percent_known >= ${MIN_KNOWN}). DO NOT hand-edit —
 * re-run the script against the public dataset. Alpha-sorted for byte-stable diffs.
 */
export const CONCRETENESS: Record<string, number> = {
${entries}
};
`;

writeFileSync('src/checks/lexicons/concreteness.ts', out);
console.error(`wrote ${picked.length} entries to src/checks/lexicons/concreteness.ts`);
